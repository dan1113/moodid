import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFile} from 'node:fs/promises';
import worker,{MoodidCounter} from '../worker/index.js';
const db=new DatabaseSync(':memory:');
const storage={sql:{exec(sql,...args){const rows=db.prepare(sql).all(...args);return {toArray:()=>rows,one:()=>{assert.equal(rows.length,1);return rows[0]}}}},transactionSync(fn){db.exec('BEGIN');try{fn();db.exec('COMMIT')}catch(e){db.exec('ROLLBACK');throw e}}};
const counter=new MoodidCounter({storage});
const env={MOODID_COUNTER:{idFromName:()=>1,get:()=>({fetch:(url,opts)=>counter.fetch(new Request(url,opts))})}};
const input=JSON.parse(await readFile(new URL('../database.json',import.meta.url)));
const answers=Object.fromEntries(input.map((d,i)=>[i,[d.options[0].id]]));
const req=(visitorId,origin='https://moodid.test',a=answers)=>new Request('https://moodid.test/api/stats',{method:'POST',headers:{Origin:origin},body:JSON.stringify({visitorId,answers:a})});
const count=async()=> (await (await worker.fetch(new Request('https://moodid.test/api/stats'),env)).json()).count;
assert.equal(await count(),0);
const id='12345678-1234-4234-8234-123456789abc';
assert.equal((await worker.fetch(req(id),env)).status,200);assert.equal(await count(),1);
await worker.fetch(req(id),env);assert.equal(await count(),1);
await worker.fetch(req('22345678-1234-4234-8234-123456789abc'),env);assert.equal(await count(),2);
assert.equal((await worker.fetch(req(id,'https://other.test'),env)).status,403);
assert.equal((await worker.fetch(req(id,'https://moodid.test',{}),env)).status,400);assert.equal(await count(),2);
const sameStore=new MoodidCounter({storage});assert.equal((await (await sameStore.fetch(new Request('https://counter/count'))).json()).count,2);
assert.equal((await worker.fetch(new Request('https://moodid.test/api/stats'),{})).status,503);
console.log('Persistent completion count, duplicate browsers, invalid answers, cross-origin rejection and missing binding handling passed.');
